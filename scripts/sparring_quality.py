"""Final assisted-sparring audit, including native baselines and move 50+.

Stockfish supplies position evidence only. Every replacement is generated by
Regicide with previously rejected roots excluded. Finite audits are not proofs.
"""
import copy
import math
import threading
import time

import chess

import sparring_evaluation
import sparring_play
import sparring_balance
import pending_exchange

POLICY = "regicide-sparring-quality-v6"
MAX_BUDGET_MS = 8000
AUDIT_MS = 650
STARTUP_ALLOWANCE_MS = 1500
MIN_BUDGET_MS = 250
MIN_NATIVE_DEPTH = 4
MIN_REFERENCE_DEPTH = 10
NOISE_CP = 20
FINISH_MAX_LOSS_CP = 40
NATIVE_BUDGETS_MS = (400, 400, 2000, 500)
NATIVE_PROMOTION_MS = 1200
MIN_CONFIRMED_NATIVE_DEPTH = 2
NATIVE_STABILITY_CP = 40
REFERENCE_STABILITY_CP = 60
MINOR_PROBE_MS = 400
MAX_MINOR_PROBES = 2
MAX_ROOK_PROBES = 1
ROOK_PROBE_MS = 400
MITIGATION_MIN_LOSS_CP = 150
MITIGATION_MIN_IMPROVEMENT_CP = 100


def _number(value):
    return type(value) in (int, float) and math.isfinite(value)


def _contact_moves(board, moves):
    """Diagnostic contacts; live origin searches keep every legal move.

    An immediate threat does not establish that a move beats a quiet defense.
    """
    contacts = []
    for move in moves:
        if (move not in board.legal_moves
                or board.piece_type_at(move.from_square) not in (chess.KNIGHT, chess.BISHOP)):
            continue
        after = board.copy(stack=False)
        after.push(move)
        if any((piece := after.piece_at(square)) is not None and piece.color != board.turn
               and piece.piece_type in (chess.KNIGHT, chess.BISHOP, chess.ROOK, chess.QUEEN)
               for square in after.attacks(move.to_square)):
            contacts.append(move)
    return contacts


def _minor_origins(board, excluded):
    represented = {candidate.from_square for candidate in excluded}
    origins = {candidate.from_square for candidate in board.legal_moves
               if candidate.from_square not in represented
               and board.piece_type_at(candidate.from_square) in (chess.KNIGHT, chess.BISHOP)}
    ordered = sorted(origins, key=lambda square: (
        0 if board.piece_type_at(square) == chess.KNIGHT else 1,
        square if board.turn else chess.square_mirror(square)))
    if sparring_play.phase(board) != "ramp":
        return ordered[:MAX_MINOR_PROBES]
    # One family cannot consume both existing slots while another is unseen.
    families = [[square for square in ordered if board.piece_type_at(square) == kind]
                for kind in (chess.BISHOP, chess.KNIGHT)]
    varied = []
    while any(families) and len(varied) < MAX_MINOR_PROBES:
        for family in families:
            if family and len(varied) < MAX_MINOR_PROBES:
                varied.append(family.pop(0))
    return varied


def _evidence(position, value, original_turn, *, terminal=False):
    if not isinstance(value, dict) or value.get("fen") != position.fen(en_passant="fen"):
        return False
    sign = 1 if original_turn else -1
    if value.get("terminal") is True:
        outcome = position.outcome(claim_draw=True)
        winner = None if outcome is None or outcome.winner is None else "white" if outcome.winner else "black"
        return bool(terminal and outcome is not None and value.get("winner") == winner
                    and value.get("outcome") == outcome.result()
                    and (winner is not None or value.get("cp_own") == 0))
    if (value.get("bound") != "exact" or type(value.get("depth")) is not int
            or value["depth"] < MIN_REFERENCE_DEPTH):
        return False
    cp, mate = value.get("cp"), value.get("mate")
    if type(cp) is int and abs(cp) <= 100000 and mate is None:
        return value.get("cp_own") == cp * sign and value.get("winner") is None
    if cp is None and type(mate) is int and 0 < abs(mate) <= 10000:
        return (value.get("mate_own") == mate * sign
                and value.get("winner") == ("white" if mate > 0 else "black"))
    return False


def verdict(board, move, assessment):
    """Use unrestricted root quality, never anchor safety to a bad baseline."""
    result = {"verified": False, "acceptable": False, "reason": "unverified_reference",
              "phase": sparring_play.phase(board), "root_cp_own": None,
              "child_cp_own": None, "loss_cp": None, "floor_cp": None,
              "tolerance_cp": NOISE_CP, "inside_close_band": False}
    if not isinstance(assessment, dict) or assessment.get("status") != "ready":
        return result
    if (assessment.get("fen") != board.fen(en_passant="fen")
            or assessment.get("history_uci") != [m.uci() for m in board.move_stack]
            or assessment.get("selected_uci") != move.uci()):
        return result
    after = board.copy(stack=True)
    after.push(move)
    root, child = assessment.get("root"), assessment.get("child")
    if not _evidence(board, root, board.turn) or not _evidence(after, child, board.turn, terminal=True):
        return result
    own = "white" if board.turn else "black"
    root_cp, child_cp = root.get("cp_own"), child.get("cp_own")
    result.update(verified=True, root_cp_own=root_cp, child_cp_own=child_cp,
                  inside_close_band=_number(child_cp) and abs(child_cp) <= 100)
    if child.get("winner") == own:
        return {**result, "acceptable": True, "reason": "winning_mate_verified"}
    if child.get("winner") is not None:
        return {**result, "reason": "losing_mate_detected"}
    if (len(board.move_stack) < sparring_play.RAMP_PLY and board.root().fen(en_passant="fen") == chess.STARTING_FEN
            and (root.get("winner") == own or _number(root_cp) and root_cp >= -80)):
        natural = pending_exchange.naturalness(board, move)
        result["naturalness"] = natural
        if natural.get("reason") in ("obvious_material_donation", "immediate_mate_reply"):
            return {**result, "floor_cp": -80, "reason": "avoidable_material_donation",
                    "loss_cp": max(0, root_cp - child_cp) if _number(root_cp) and _number(child_cp) else None}
    if root.get("winner") == own:
        if (len(board.move_stack) < sparring_play.RAMP_PLY and board.root().fen(en_passant="fen") == chess.STARTING_FEN
                and _number(child_cp)):
            return {**result, "acceptable": child_cp >= -100, "floor_cp": -80,
                    "reason": "early_winning_mate_deferred" if child_cp >= -100 else "position_collapse_detected"}
        return {**result, "reason": "forced_win_lost"}
    if root.get("winner") is not None:
        return {**result, "acceptable": True, "reason": "escaped_reference_mate"}
    if not _number(root_cp) or not _number(child_cp):
        return {**result, "verified": False, "reason": "uncomparable_reference"}
    if len(board.move_stack) < sparring_play.RAMP_PLY:
        # A sound concession may reduce a large advantage. It must not turn
        # a holdable position into a losing one; behind, preserve resistance.
        floor = -80 if root_cp >= -80 else root_cp - 40
    elif len(board.move_stack) < sparring_play.FINISH_PLY:
        floor = sparring_play.ramp_guard(board, root_cp)["floor_cp"]
    else:
        floor = root_cp - FINISH_MAX_LOSS_CP
    effective_floor = floor - NOISE_CP
    if result["phase"] == "ramp" and root_cp >= 0:
        # The comparison noise margin must not authorize turning a holdable
        # position into a negative one after the close phase has ended.
        effective_floor = max(0, effective_floor)
    result.update(floor_cp=floor, effective_floor_cp=effective_floor,
                  loss_cp=max(0, root_cp - child_cp))
    result.update(acceptable=child_cp >= effective_floor,
                  reason="reference_floor_met" if child_cp >= effective_floor else "position_collapse_detected")
    return result


def verify(board, move, search, close_engine, assess, *, budget_ms=MAX_BUDGET_MS, cancelled=None):
    started = time.monotonic()
    receipt = {"policy": POLICY, "status": "skipped", "reason": "insufficient_budget",
               "original_uci": move.uci(), "selected_uci": move.uci(),
               "before_fen": board.fen(en_passant="fen"),
               "history_uci": [m.uci() for m in board.move_stack],
               "phase": sparring_play.phase(board), "budget_ms": budget_ms,
               "elapsed_ms": 0, "audit_ms": AUDIT_MS, "startup_allowance_ms": STARTUP_ALLOWANCE_MS,
               "repair_attempted": False, "applied": False,
               "initial": None, "initial_verdict": None, "final_verdict": None,
               "mitigation": None,
               "attempts": [], "scope": "externally verified native candidates; not standalone engine strength"}
    if not _number(budget_ms) or budget_ms < MIN_BUDGET_MS:
        return None, receipt, False
    budget_ms = min(budget_ms, MAX_BUDGET_MS)
    deadline = started + budget_ms / 1000
    done, lock = threading.Event(), threading.Lock()
    active, discarded, failure = [False], [False], [None]
    stage_deadline = [deadline]

    def interrupted():
        try:
            return bool(cancelled and cancelled())
        except Exception:
            return True

    def stop(reason):
        with lock:
            if failure[0] is None:
                failure[0] = reason
            close = active[0] and not discarded[0]
            if close:
                discarded[0] = True
        if close:
            try:
                close_engine()
            except Exception:
                pass

    def check():
        if interrupted():
            stop("cancelled")
        if time.monotonic() >= deadline:
            stop("budget_exhausted")
        if failure[0]:
            raise InterruptedError(failure[0])

    def watch():
        while not done.wait(.01):
            if interrupted():
                stop("cancelled")
            elif time.monotonic() > min(deadline, stage_deadline[0]) + .10:
                stop("native_timeout" if active[0] else "budget_exhausted")

    def audit(candidate, *, first=False):
        check()
        amount = min(AUDIT_MS + (STARTUP_ALLOWANCE_MS if first else 0),
                     int((deadline - time.monotonic()) * 1000))
        if amount < MIN_BUDGET_MS:
            raise TimeoutError("insufficient_audit_budget")
        data = assess(candidate, amount, lambda: interrupted() or time.monotonic() >= deadline)
        check()
        return data, verdict(board, candidate, data)

    def native_search(amount, allowed, **options):
        check()
        with lock:
            active[0] = True
            stage_deadline[0] = time.monotonic() + amount / 1000
        try:
            value = search(amount, root_moves=allowed, fresh=True, publish=False, **options)
        finally:
            with lock:
                active[0] = False
                stage_deadline[0] = deadline
        check()
        return value

    def native_evidence(candidate, allowed):
        reply, final, packets = candidate
        if not isinstance(reply.move, chess.Move) or reply.move not in allowed:
            raise ValueError("invalid_native_candidate")
        sample = sparring_evaluation.validate_packet(board, final)
        complete = (sparring_evaluation.validate_packet(board, packets.get(final.get("depth")))
                    if isinstance(final, dict) and isinstance(packets, dict) else None)
        if sample is None or sample != complete or sample["root"] != reply.move.uci():
            return None
        return sample

    def confirmed_shallow_repair(candidate, discovery, promoted, candidate_verdict, checked, attempt):
        """A separately labelled external confirmation, never native depth four.

        Some completed native iterations stop at the quiescence safety limit.
        A shallow proposal can only repair an already unsafe pre-16 incumbent,
        with two stable native completions and two central-band references.
        Elective concessions and all later phases retain the depth-four rule.
        """
        initial_verdict = receipt["initial_verdict"]
        cp = candidate_verdict.get("child_cp_own")
        if (len(board.move_stack) >= sparring_play.RAMP_PLY or board.root().fen(en_passant="fen") != chess.STARTING_FEN
                or len(attempt.get("allowed_uci", [])) < 2
                or initial_verdict.get("acceptable") or not initial_verdict.get("verified")
                or not _number(initial_verdict.get("child_cp_own")) or initial_verdict["child_cp_own"] >= -100
                or not candidate_verdict.get("verified") or not candidate_verdict.get("acceptable")
                or not _number(cp) or abs(cp) > sparring_balance.BUFFER_CP
                or not all(isinstance(value, dict) and value.get("depth", 0) >= MIN_CONFIRMED_NATIVE_DEPTH
                           and _number(value.get("cp")) and value.get("mate") is None
                           for value in (discovery, promoted))
                or discovery.get("root") != candidate.uci() or promoted.get("root") != candidate.uci()
                or abs(discovery["cp"] - promoted["cp"]) > NATIVE_STABILITY_CP):
            return None
        natural = sparring_play.naturalness(board, candidate)
        if not natural["admitted"]:
            attempt["confirmation_rejected"] = "elective_piece_donation"
            return None
        repeated, repeated_verdict = audit(candidate)
        check()  # Cancellation invalidates even a fully completed confirmation.
        root, repeated_root = checked.get("root") or {}, repeated.get("root") or {}
        reference_roots = (receipt["initial"].get("root") or {}, root, repeated_root)
        root_scores = [value.get("cp_own") for value in reference_roots]
        repeated_cp = repeated_verdict.get("child_cp_own")
        valid = (repeated_verdict.get("verified") and repeated_verdict.get("acceptable")
                 and _number(repeated_cp) and abs(repeated_cp) <= sparring_balance.BUFFER_CP
                 and abs(repeated_cp - cp) <= REFERENCE_STABILITY_CP
                 and all(_number(value) for value in root_scores)
                 and max(root_scores) - min(root_scores) <= 100
                 and abs(root_scores[1] - root_scores[2]) <= REFERENCE_STABILITY_CP
                 and all(value.get("winner") is None for value in reference_roots))
        if valid:
            repeated_verdict["floor_cp"] = max(value for value in (
                initial_verdict.get("floor_cp"), candidate_verdict.get("floor_cp"),
                repeated_verdict.get("floor_cp")) if _number(value))
            valid = repeated_cp >= repeated_verdict["floor_cp"] - NOISE_CP
            repeated_verdict["acceptable"] = bool(valid)
        attempt["reference_confirmation"] = {
            "kind": "reference_confirmed_native_candidate", "verified": bool(valid),
            "native_completed_depths": [discovery["depth"], promoted["depth"]],
            "native_score_delta_cp": abs(discovery["cp"] - promoted["cp"]),
            "first_child_cp_own": cp, "second_child_cp_own": repeated_cp,
            "naturalness": natural, "assessment": repeated, "verdict": repeated_verdict,
            "scope": "two external confirmations of a native proposal; not a native depth-four completion"}
        return repeated_verdict if valid else None

    replacement = None
    best_mitigation = None
    best_balance = None
    best_safe_repair = None

    def apply_safe_repair(stopped_reason=None):
        nonlocal replacement
        candidate, selected_verdict, attempt_index = best_safe_repair
        replacement = candidate
        receipt.update(status="replaced", reason="verified_native_repair", applied=True,
                       selected_uci=candidate[0].move.uci(), final_verdict=copy.deepcopy(selected_verdict),
                       repair_margin={"status": "outside_buffer", "buffer_cp": sparring_balance.BUFFER_CP,
                                      "attempt_index": attempt_index, "stopped_reason": stopped_reason})

    def remember_balance(candidate, balance):
        nonlocal best_balance
        best_balance = (candidate, balance)

    def apply_balance(candidate, balance, stopped_reason=None):
        nonlocal replacement
        replacement, selected_verdict, _ = candidate
        receipt["balance"] = copy.deepcopy(balance)
        if stopped_reason is not None:
            receipt["balance"]["stopped_reason"] = stopped_reason
        receipt.update(status="balanced" if balance["status"] == "met" else "balance_improved",
                       reason=balance["reason"], applied=True,
                       selected_uci=replacement[0].move.uci(), final_verdict=selected_verdict)

    def apply_mitigation(stopped_reason=None):
        nonlocal replacement
        candidate, candidate_verdict, improvement, attempt_index = best_mitigation
        replacement = candidate
        receipt.update(status="mitigated", reason="verified_native_damage_limitation", applied=True,
                       selected_uci=candidate[0].move.uci(), final_verdict=copy.deepcopy(candidate_verdict),
                       mitigation={"original_child_cp_own": receipt["initial_verdict"]["child_cp_own"],
                                   "selected_child_cp_own": candidate_verdict["child_cp_own"],
                                   "improvement_cp": improvement,
                                   "minimum_improvement_cp": MITIGATION_MIN_IMPROVEMENT_CP,
                                   "minimum_original_loss_cp": MITIGATION_MIN_LOSS_CP,
                                   "attempt_index": attempt_index, "floor_met": False,
                                   "stopped_reason": stopped_reason,
                                   "scope": "verified reduction of loss; reference floor remains unmet"})

    watcher = threading.Thread(target=watch, name="regicide-quality-guard", daemon=True)
    watcher.start()
    try:
        initial, initial_verdict = audit(move, first=True)
        receipt.update(initial=initial, initial_verdict=initial_verdict, final_verdict=initial_verdict)
        early_resistance = (len(board.move_stack) < sparring_play.RAMP_PLY
                            and board.root().fen(en_passant="fen") == chess.STARTING_FEN
                            and initial_verdict["verified"] and initial_verdict["acceptable"]
                            and _number(initial_verdict["child_cp_own"])
                            and initial_verdict["child_cp_own"] < -sparring_balance.BUFFER_CP)
        run_repair = False
        if not initial_verdict["verified"]:
            receipt.update(status="unverified", reason="incumbent_reference_unverified")
        elif sparring_balance.required(board, initial_verdict, initial):
            receipt.update(status="verified" if initial_verdict["acceptable"] else "unverified",
                           reason=initial_verdict["reason"], repair_attempted=True)
            balanced, balance = sparring_balance.recover(
                board, move, initial, initial_verdict, native_search=native_search,
                native_evidence=native_evidence, audit=audit, check=check, deadline=deadline,
                minimum_native_depth=MIN_NATIVE_DEPTH, completed=remember_balance)
            receipt["balance"] = balance
            if balanced is not None:
                apply_balance(balanced, balance)
            elif not initial_verdict["acceptable"]:
                run_repair = True
        elif initial_verdict["acceptable"] and not early_resistance:
            receipt.update(status="verified", reason=initial_verdict["reason"])
        else:
            run_repair = True
        if run_repair:
            receipt.update(status="unverified", reason="no_verified_native_repair", repair_attempted=True)
            if early_resistance:
                receipt["balance"] = {"active": True, "direction": "behind", "status": "unmet",
                                      "reason": "strongest_native_resistance_requested",
                                      "original_child_cp_own": initial_verdict["child_cp_own"]}
            excluded = {move}

            def probes():
                for index, allocation in enumerate(NATIVE_BUDGETS_MS):
                    if index == 1 and len(board.move_stack) < sparring_play.RAMP_PLY and MAX_ROOK_PROBES:
                        represented = {candidate.from_square for candidate in excluded}
                        rooks = {candidate.from_square for candidate in board.legal_moves
                                 if candidate.from_square not in represented
                                 and board.piece_type_at(candidate.from_square) == chess.ROOK}
                        if rooks:
                            # Prefer a rook already working on a central file,
                            # rather than always taking the corner rook first.
                            origin = min(rooks, key=lambda square: (
                                abs(chess.square_file(square) - 3.5),
                                square if board.turn else chess.square_mirror(square)))
                            yield ROOK_PROBE_MS, "rook_origin", origin
                            continue  # Replaces one global probe; no extra time slot.
                    if index == 2:
                        # Repeated unrestricted searches can keep ranking the
                        # same piece's moves too highly. Let the native engine
                        # compare each unseen minor piece's legal choices.
                        origins = _minor_origins(board, excluded)
                        for origin in origins:
                            # Keep quiet defense/outpost moves in the same
                            # bounded search as attacks from this piece.
                            yield MINOR_PROBE_MS, "minor_origin", origin
                        if origins:
                            allocation = min(allocation, MINOR_PROBE_MS)
                    yield allocation, "global", None

            for allocation, kind, origin in probes():
                check()
                allowed = [candidate for candidate in board.legal_moves if candidate not in excluded
                           and (origin is None or candidate.from_square == origin)]
                amount = min(allocation, (deadline - time.monotonic()) * 1000 - AUDIT_MS - 50)
                if not allowed or amount < 100:
                    break
                attempt = {"budget_ms": round(amount, 3), "excluded_uci": sorted(m.uci() for m in excluded),
                           "kind": kind, "origin": chess.square_name(origin) if origin is not None else None,
                           "allowed_uci": [candidate.uci() for candidate in allowed],
                           "native_evidence": None, "discovery_evidence": None,
                           "native_promotion": None, "assessment": None, "verdict": None}
                receipt["attempts"].append(attempt)
                candidate = native_search(amount, allowed)
                reply, final, packets = candidate
                sample = native_evidence(candidate, allowed)
                excluded.add(reply.move)
                if sample is None:
                    attempt["reason"] = "incomplete_native_candidate"
                    continue
                attempt["discovery_evidence"] = copy.deepcopy(sample)
                if sample["depth"] >= MIN_NATIVE_DEPTH:
                    attempt["native_evidence"] = copy.deepcopy(sample)
                checked, candidate_verdict = audit(reply.move)
                attempt.update(assessment=checked, verdict=candidate_verdict)
                if candidate_verdict.get("reason") == "avoidable_material_donation":
                    attempt["reason"] = "avoidable_material_donation"
                    continue
                # Avoid accepting a locally good-looking child when repeated
                # root searches disagree about whether the position is won.
                if (candidate_verdict["verified"] and _number(initial_verdict["root_cp_own"])
                        and _number(candidate_verdict["root_cp_own"])
                        and abs(initial_verdict["root_cp_own"] - candidate_verdict["root_cp_own"]) > 100):
                    attempt["reason"] = "reference_root_disagreement"
                    continue
                if (candidate_verdict["verified"] and initial["root"].get("winner")
                        != checked["root"].get("winner")):
                    attempt["reason"] = "reference_root_disagreement"
                    continue
                # Repeat searches may move the root estimate slightly. Never
                # use that drift to relax the original position's safety floor.
                if (candidate_verdict["verified"] and _number(initial_verdict["floor_cp"])
                        and _number(candidate_verdict["floor_cp"])):
                    floor = max(initial_verdict["floor_cp"], candidate_verdict["floor_cp"])
                    candidate_verdict["floor_cp"] = floor
                    effective = max([floor - NOISE_CP] + [value for value in (
                        initial_verdict.get("effective_floor_cp"),
                        candidate_verdict.get("effective_floor_cp")) if _number(value)])
                    candidate_verdict["effective_floor_cp"] = effective
                    candidate_verdict["acceptable"] = candidate_verdict["child_cp_own"] >= effective
                    if not candidate_verdict["acceptable"]:
                        candidate_verdict["reason"] = "position_collapse_detected"
                acceptable = candidate_verdict["verified"] and candidate_verdict["acceptable"]
                if early_resistance and acceptable:
                    cp = candidate_verdict["child_cp_own"]
                    acceptable = (_number(cp) and (cp >= -sparring_balance.BUFFER_CP
                                  or cp >= initial_verdict["child_cp_own"] + NOISE_CP))
                    if not acceptable:
                        attempt["reason"] = "no_clear_resistance_improvement"
                improvement = None
                if (candidate_verdict["verified"] and not acceptable
                        and _number(initial_verdict["loss_cp"])
                        and initial_verdict["loss_cp"] >= MITIGATION_MIN_LOSS_CP
                        and _number(initial_verdict["child_cp_own"])
                        and _number(candidate_verdict["child_cp_own"])):
                    delta = candidate_verdict["child_cp_own"] - initial_verdict["child_cp_own"]
                    if delta >= MITIGATION_MIN_IMPROVEMENT_CP:
                        improvement = delta
                attempt.update(mitigation_eligible=improvement is not None, improvement_cp=improvement)
                if not acceptable and improvement is None:
                    continue
                if sample["depth"] < MIN_NATIVE_DEPTH:
                    promotion_ms = min(NATIVE_PROMOTION_MS, (deadline - time.monotonic()) * 1000 - 25)
                    if promotion_ms < 100:
                        attempt["reason"] = "native_promotion_budget_missing"
                        continue
                    promotion = {"budget_ms": round(promotion_ms, 3), "evidence": None, "status": "unverified",
                                 "kind": "promotion", "origin": chess.square_name(reply.move.from_square),
                                 "allowed_uci": [reply.move.uci()]}
                    attempt["native_promotion"] = promotion
                    promoted = native_search(promotion_ms, [reply.move])
                    evidence = native_evidence(promoted, [reply.move])
                    if evidence is None or evidence["depth"] < MIN_NATIVE_DEPTH:
                        confirmed = confirmed_shallow_repair(
                            reply.move, sample, evidence, candidate_verdict, checked, attempt)
                        if confirmed is None:
                            attempt["reason"] = "incomplete_native_promotion"
                            continue
                        promotion.update(evidence=copy.deepcopy(evidence), status="reference_confirmed",
                                         evidence_kind="reference_confirmed_native_candidate")
                        attempt["native_evidence"] = copy.deepcopy(evidence)
                        attempt["evidence_kind"] = "reference_confirmed_native_candidate"
                        candidate_verdict = confirmed
                        candidate = promoted
                        acceptable = True
                    else:
                        promotion.update(evidence=copy.deepcopy(evidence), status="verified")
                        attempt["native_evidence"] = copy.deepcopy(evidence)
                        candidate = promoted
                if acceptable:
                    cp = candidate_verdict.get("child_cp_own")
                    if (len(board.move_stack) < sparring_play.RAMP_PLY and board.root().fen(en_passant="fen") == chess.STARTING_FEN
                            and _number(cp) and cp >= -100 and abs(cp) > sparring_balance.BUFFER_CP):
                        attempt["reason"] = "verified_repair_outside_buffer"
                        if (best_safe_repair is None or abs(cp - sparring_balance.TARGET_CP)
                                < abs(best_safe_repair[1]["child_cp_own"] - sparring_balance.TARGET_CP)):
                            best_safe_repair = (candidate, copy.deepcopy(candidate_verdict), len(receipt["attempts"]) - 1)
                        continue
                    replacement = candidate
                    receipt.update(status="replaced", reason="verified_native_repair", applied=True,
                                   selected_uci=reply.move.uci(), final_verdict=candidate_verdict)
                    if early_resistance:
                        receipt["balance"].update(status="met" if abs(candidate_verdict["child_cp_own"]) <= 80 else "improved",
                                                  reason="verified_native_resistance",
                                                  selected_child_cp_own=candidate_verdict["child_cp_own"])
                    break
                if (best_mitigation is None or candidate_verdict["child_cp_own"]
                        > best_mitigation[1]["child_cp_own"]):
                    best_mitigation = (candidate, copy.deepcopy(candidate_verdict), improvement,
                                       len(receipt["attempts"]) - 1)
            check()
            if replacement is None and best_safe_repair is not None:
                apply_safe_repair()
            elif replacement is None and best_mitigation is not None:
                apply_mitigation()
            elif early_resistance and replacement is None:
                receipt.update(status="verified", reason="verified_resistance_preserved")
    except Exception as exc:
        replacement = None
        receipt.update(status="unverified", reason=failure[0] or str(exc), applied=False,
                       selected_uci=move.uci(), final_verdict=receipt["initial_verdict"], error=type(exc).__name__)
        # Only previously completed evidence survives optional work running
        # out of time. A user, clock or context cancellation always wins.
        if (best_safe_repair is not None and failure[0] in ("budget_exhausted", "native_timeout")
                and not interrupted()):
            apply_safe_repair(failure[0])
        elif (best_mitigation is not None and failure[0] in ("budget_exhausted", "native_timeout")
                and not interrupted()):
            apply_mitigation(failure[0])
        elif (best_balance is not None and failure[0] in ("budget_exhausted", "native_timeout")
                and not interrupted()):
            apply_balance(*best_balance, stopped_reason=failure[0])
    finally:
        done.set()
        watcher.join(timeout=.2)
        receipt["elapsed_ms"] = round((time.monotonic() - started) * 1000, 3)
    return replacement, receipt, discarded[0]
